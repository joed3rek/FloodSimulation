"""Build the Grasshopper component scripts: each ``src/*.py`` with the API client inlined.

    python -m spongepark.rhino.grasshopper.build

writes ``components/<name>.py``. In Grasshopper (Rhino 8): add a Script component, choose Python 3,
paste the file, and create the inputs and outputs listed in its docstring.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).parent


def build(out: Path = HERE / "components") -> list:
    client = (HERE / "_client.py").read_text(encoding="utf-8")
    client = client[client.index('"""', 3) + 3:].strip()  # drop the module docstring
    out.mkdir(exist_ok=True)
    written = []
    for src in sorted((HERE / "src").glob("*.py")):
        body = src.read_text(encoding="utf-8")
        doc_end = body.index('"""', 3) + 3
        text = (body[:doc_end] + "\n# --- spongepark engine API client (generated by build.py; edit _client.py) ---\n"
                + client + "\n# --- component ---\n" + body[doc_end:].lstrip("\n"))
        target = out / src.name.split("_", 1)[1]
        target.write_text(text, encoding="utf-8")
        written.append(target)
    return written


if __name__ == "__main__":
    for p in build():
        print(p)
