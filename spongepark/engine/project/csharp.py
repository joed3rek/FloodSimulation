"""Generate the Unity C# data classes from the shared JSON Schema (``schema/sponge.schema.json``).

``spongepark schema csharp`` writes ``unity/SpongeParkApp/Assets/SpongePark/Core/Data/SpongeSchema.g.cs``.
Each schema definition becomes a class with the same JSON property names (Newtonsoft attributes);
every class keeps unknown fields in ``Extra`` ([JsonExtensionData]) so a round trip loses nothing.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Dict, List

from .jsonschema import REPO, SCHEMA_PATH

CS_PATH = REPO / "unity" / "SpongeParkApp" / "Assets" / "SpongePark" / "Core" / "Data" / "SpongeSchema.g.cs"


def _pascal(name: str) -> str:
    out = "".join(w[:1].upper() + w[1:] for w in re.split(r"[_\W]+", name) if w)
    return ("_" + out) if out[:1].isdigit() else out


def _cs_type(s: Dict[str, Any]) -> str:
    """C# type for a property schema (value types nullable so absent stays absent)."""
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "anyOf" in s:
        opts = [o for o in s["anyOf"] if o.get("type") != "null"]
        return _cs_type(opts[0]) if len(opts) == 1 else "JToken"
    t = s.get("type")
    if t == "string":
        return "string"
    if t == "number":
        return "double?"
    if t == "integer":
        return "long?"
    if t == "boolean":
        return "bool?"
    if t == "array":
        return f"List<{_cs_type(s.get('items', {})).rstrip('?')}>"
    if t == "object":
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Dictionary<string, {_cs_type(ap).rstrip('?')}>"
        return "Dictionary<string, JToken>"
    return "JToken"


def _init(cs: str, s: Dict[str, Any]) -> str:
    """Initialiser for collections that Python always writes (lists and maps with a default)."""
    if cs.startswith(("List<", "Dictionary<")) and s.get("default") in ([], {}):
        return " = new " + cs + "();"
    return ""


def generate() -> str:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    lines: List[str] = [
        "// <auto-generated>",
        "// Generated by `spongepark schema csharp` from schema/sponge.schema.json "
        f"(schema {schema['version']}). Do not edit: change spongepark/engine/project/schema.py and regenerate.",
        "// </auto-generated>",
        "using System.Collections.Generic;",
        "using Newtonsoft.Json;",
        "using Newtonsoft.Json.Linq;",
        "",
        "namespace SpongePark.Data",
        "{",
        "    public static class SchemaInfo",
        "    {",
        f"        public const string Version = \"{schema['version']}\";",
        "    }",
    ]
    for name, d in sorted(schema["$defs"].items()):
        lines.append("")
        if d.get("description"):
            for dl in d["description"].strip().splitlines():
                lines.append(f"    /// {dl.strip()}")
        lines.append(f"    public partial class {name}")
        lines.append("    {")
        for prop, ps in d.get("properties", {}).items():
            cs = _cs_type(ps)
            lines.append(f"        [JsonProperty(\"{prop}\")] public {cs} {_pascal(prop)} {{ get; set; }}{_init(cs, ps)}")
        lines.append("        /// Fields this version does not know about, kept as they are.")
        lines.append("        [JsonExtensionData] public IDictionary<string, JToken> Extra { get; set; } = new Dictionary<string, JToken>();")
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def write(path: Path = CS_PATH) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate(), encoding="utf-8")
    return path
